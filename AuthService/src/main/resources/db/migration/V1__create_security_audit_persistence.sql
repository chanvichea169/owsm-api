    IF to_regclass('tbl_users') IS NOT NULL THEN
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_login_audit_user') THEN
            ALTER TABLE login_audit
                ADD CONSTRAINT fk_login_audit_user FOREIGN KEY (user_id)
                REFERENCES tbl_users (id) ON DELETE SET NULL;
        END IF;
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_security_audit_user') THEN
            ALTER TABLE security_audit
                ADD CONSTRAINT fk_security_audit_user FOREIGN KEY (user_id)
                REFERENCES tbl_users (id) ON DELETE SET NULL;
        END IF;
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_auth_device_user') THEN
            ALTER TABLE auth_device
                ADD CONSTRAINT fk_auth_device_user FOREIGN KEY (user_id)
                REFERENCES tbl_users (id) ON DELETE SET NULL;
        END IF;
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_auth_session_user') THEN
            ALTER TABLE auth_session
                ADD CONSTRAINT fk_auth_session_user FOREIGN KEY (user_id)
                REFERENCES tbl_users (id) ON DELETE SET NULL;
        END IF;
